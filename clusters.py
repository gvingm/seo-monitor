# Скомпилированные регулярки для скорости
_COMPILED: list[tuple[str, str, str, list[re.Pattern]]] = []
for _c in CLUSTERS:
    _COMPILED.append((
        _c["id"],
        _c["label"],
        _c["emoji"],
        [re.compile(p, re.IGNORECASE) for p in _c["patterns"]],
    ))


def detect_cluster(keyword: str) -> Optional[str]:
    """Возвращает cluster_id или None если не определён.

    Применяет правила в порядке определения — первый матч выигрывает.
    """
    if not keyword:
        return None
    kw = keyword.lower().strip()
    for cid, _label, _emoji, patterns in _COMPILED:
        for p in patterns:
            if p.search(kw):
                return cid
    return None


def list_all_clusters() -> list[dict]:
    """Список всех 6 кластеров с id, label, emoji."""
    return [
        {"id": c["id"], "label": c["label"], "emoji": c["emoji"]}
        for c in CLUSTERS
    ]


